"""Language-independent checks: duplicated blocks, unused dependencies, entry points."""

from __future__ import annotations

import ast
import json
import re
import textwrap
import tomllib
import warnings

from .models import Capability, Finding, Project, SourceFile
from .scan import line_of

# fmt: off
WINDOW = 6  # identical normalised lines in a row that count as a duplicated block
TRIVIAL_LINE = re.compile(
    r"^[\s()\[\]{};,:]*$|^(else|try|finally|pass|return|break|continue|end|fi|done|esac|default)\b\W*$"
)
IMPORT_LINE = re.compile(r"^(import|from|#include|using|require|package|use)\b")
CLOSING_TAG = re.compile(r"^(</[\w.:-]*>|/>)$")  # JSX/HTML closers carry no logic
# pip-compile / pip freeze output lists transitive pins; the real declarations live elsewhere.
LOCKFILE = re.compile(r"#\s+via\b|--hash=|autogenerated by pip-compile")

# Distribution name -> import name, where the two differ in a way rules can't guess.
IMPORT_ALIASES = {
    "pyyaml": "yaml", "beautifulsoup4": "bs4", "scikit_learn": "sklearn", "pillow": "pil",
    "opencv_python": "cv2", "opencv_python_headless": "cv2", "pyjwt": "jwt",
    "protobuf": "google_protobuf", "psycopg2_binary": "psycopg2", "attrs": "attr",
    "pymupdf": "fitz", "faiss_cpu": "faiss", "faiss_gpu": "faiss", "grpcio": "grpc",
    "pyzmq": "zmq", "pycryptodome": "crypto", "dnspython": "dns", "pyserial": "serial",
    "websocket_client": "websocket", "mysqlclient": "mysqldb", "msgpack_python": "msgpack",
}
# Used at runtime without an import (servers, DB drivers behind URLs, plugins, tooling).
IMPLICIT_DEPENDENCIES = {
    "uvicorn", "gunicorn", "hypercorn", "daphne", "psycopg2", "psycopg2_binary", "psycopg",
    "psycopg_binary", "pymysql", "mysqlclient", "asyncpg", "aiosqlite", "python_multipart",
    "email_validator", "alembic", "setuptools", "wheel", "pip", "certifi", "gevent", "eventlet",
}
TOOLING_PREFIXES = ("types_", "pytest", "sphinx", "mkdocs", "flake8", "ruff", "black", "mypy",
                    "pylint", "isort", "pre_commit", "tox", "nox", "coverage")

ROUTE_PATTERNS = [
    ({"javascript", "typescript"}, "http-route",
     r"\b(?:app|router|server|api|fastify|routes?)\.(?:get|post|put|patch|delete|all)\(\s*['\"`]/"),
    ({"javascript", "typescript"}, "cli-command", r"\.command\(\s*['\"`]"),
    ({"go"}, "http-route",
     r"\b(?:HandleFunc|Handle)\(\s*\"/|\.(?:GET|POST|PUT|PATCH|DELETE|Any)\(\s*\"/"),
    ({"go"}, "cli-command", r"&cobra\.Command\{"),
    ({"java", "kotlin"}, "http-route", r"@(?:Get|Post|Put|Patch|Delete)Mapping\b"),
    ({"csharp"}, "http-route",
     r"\[Http(?:Get|Post|Put|Patch|Delete)\b|\.Map(?:Get|Post|Put|Patch|Delete)\(\s*\""),
    ({"php"}, "http-route", r"Route::(?:get|post|put|patch|delete|any)\("),
    ({"ruby"}, "http-route", r"^\s*(?:get|post|put|patch|delete)\s+['\"]/"),
]
# Comments that look like code but are directives or notes, not commented-out code.
DIRECTIVE = re.compile(
    r"^(type:|noqa|pylint:|pyright:|mypy:|fmt:|isort:|ruff:|pragma|nosec|-\*-|!|todo|fixme|"
    r"note|xxx|hack|eslint|prettier|@ts-|istanbul|c8 )",
    re.IGNORECASE,
)
STRONG_CODE = (ast.Assign, ast.AugAssign, ast.Import, ast.ImportFrom, ast.Return, ast.Raise,
               ast.Delete, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.If, ast.For,
               ast.While, ast.With, ast.Try)
# `x = y;`, `call(args);`, `return x;` or a closing bracket, as the whole comment.
C_STYLE_CODE = re.compile(
    r"^(?:(?:[\w$<>\[\],.]+\s+)?[\w$.\[\]]+\s*[-+*/]?=[^=].*"  # [type] target = value
    r"|[\w$.]+\(.*\)|return\b.*|[}\])].*)\s*;?\s*[{;]?$"  # call(...), return, closer
)
C_STYLE_LANGUAGES = {"javascript", "typescript", "go", "java", "kotlin", "scala", "csharp", "rust",
                     "swift", "c", "cpp", "php"}
# fmt: on
COMPILED_PATTERNS = [(langs, kind, re.compile(p)) for langs, kind, p in ROUTE_PATTERNS]


def duplicate_code(files: list[SourceFile]) -> list[Finding]:
    """Blocks of >= WINDOW identical (whitespace-normalised) lines; the first copy is kept."""
    seen: dict[tuple[str, ...], tuple[str, int, int]] = {}
    found = []
    for f in sorted(files, key=lambda f: f.path):
        entries, signatures = [], _signature_lines(f)
        for number in sorted(f.code_lines - signatures):
            text = " ".join(f.lines[number - 1].split())
            if not (TRIVIAL_LINE.match(text) or IMPORT_LINE.match(text) or CLOSING_TAG.match(text)):
                entries.append((number, text))
        origin_of: dict[int, tuple[str, int]] = {}
        for i in range(len(entries) - WINDOW + 1):
            key = tuple(text for _, text in entries[i : i + WINDOW])
            origin = seen.get(key)
            if origin is None:
                seen[key] = (f.path, i, entries[i][0])
            elif origin[0] != f.path or i - origin[1] >= WINDOW:  # not an overlapping self-match
                for j in range(i, i + WINDOW):
                    origin_of.setdefault(j, (origin[0], origin[2]))
        found += _duplicate_blocks(f, entries, origin_of)
    return found


def commented_out_code(files: list[SourceFile]) -> list[Finding]:
    """C5: comment blocks that are code. Python comments are checked by parsing them."""
    found = []
    for f in files:
        if f.language == "python":
            prefix, judge = "#", _python_comment_code
        elif f.language in C_STYLE_LANGUAGES:
            prefix, judge = "//", _c_style_comment_code
        else:
            continue
        for block in _comment_blocks(f, prefix):
            strong = judge(block)  # line number -> is it unmistakably code?
            if len(strong) * 2 <= sum(1 for _, text in block if text.strip()):
                continue  # mostly prose: an explanation with an example, not dead code
            for run in _runs(sorted(strong)):
                if len(run) >= 2 or strong[run[0]]:
                    found.append(
                        Finding(
                            "commented-out-code",
                            f.path,
                            run[0],
                            f"lines {run[0]}-{run[-1]}",
                            "commented-out code; version control remembers it",
                            ((run[0], run[-1]),),
                        )
                    )
    return found


def _comment_blocks(f: SourceFile, prefix: str) -> list[list[tuple[int, str]]]:
    blocks, current = [], []
    for number, line in enumerate(f.lines, start=1):
        text = line.strip()
        content = text[len(prefix) :]
        content = content[1:] if content.startswith(" ") else content
        if number in f.code_lines or not text.startswith(prefix) or DIRECTIVE.match(content):
            if current:
                blocks.append(current)
            current = []
        else:
            current.append((number, content))
    return [*blocks, current] if current else blocks


def _python_comment_code(block: list[tuple[int, str]]) -> dict[int, bool]:
    tree = _parse("\n".join(content for _, content in block))
    if tree is not None:  # the whole block is Python: keep the lines of code-like statements
        return {
            block[i][0]: kind
            for stmt in tree.body
            if (kind := _code_kind(stmt)) is not None
            for i in range(stmt.lineno - 1, stmt.end_lineno or stmt.lineno)
        }
    lines = {}
    for number, content in block:
        tree = _parse(content.strip())
        kinds = [_code_kind(stmt) for stmt in tree.body] if tree else []
        if kinds and None not in kinds:
            lines[number] = any(kinds)
    return lines


def _code_kind(stmt: ast.stmt) -> bool | None:
    """True: unmistakably code; False: a bare call (prose can parse as one); None: not code."""
    if isinstance(stmt, STRONG_CODE) or (isinstance(stmt, ast.AnnAssign) and stmt.value):
        return True
    if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call | ast.Await):
        return False
    return None


def _c_style_comment_code(block: list[tuple[int, str]]) -> dict[int, bool]:
    return {
        number: content.rstrip().endswith((";", "{", "}"))
        for number, content in block
        if C_STYLE_CODE.match(content.strip())
    }


def _parse(text: str) -> ast.Module | None:
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            tree = ast.parse(textwrap.dedent(text))
    except (SyntaxError, ValueError):
        return None
    return tree if tree.body else None


def _runs(numbers: list[int]) -> list[list[int]]:
    runs: list[list[int]] = []
    for n in numbers:
        if runs and n == runs[-1][-1] + 1:
            runs[-1].append(n)
        else:
            runs.append([n])
    return runs


def _signature_lines(f: SourceFile) -> set[int]:
    """Lines of multi-line ``def`` headers: typed parameter lists repeat without being logic."""
    lines = set()
    for node in ast.walk(f.tree) if f.tree else ():
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and node.body:
            lines.update(range(node.lineno, node.body[0].lineno))
    return lines


def _duplicate_blocks(
    f: SourceFile, entries, origin_of: dict[int, tuple[str, int]]
) -> list[Finding]:
    found = []
    for block in _runs(sorted(origin_of)):
        start, end = entries[block[0]][0], entries[block[-1]][0]
        path, line = origin_of[block[0]]
        found.append(
            Finding(
                "duplicate-code",
                f.path,
                start,
                f"lines {start}-{end}",
                f"repeats {path}:{line}",
                ((start, end),),
            )
        )
    return found


def unused_dependencies(project: Project, python_imports: set[str]) -> tuple[list[Finding], int]:
    """Declared runtime dependencies nothing imports or invokes -> (findings, declared count)."""
    python_deps = _python_dependencies(project)
    js_deps, js_scripts = _js_dependencies(project)
    import_keys = {
        _normalise("_".join(parts[:k]))
        for module in python_imports
        for parts in [module.split(".")]
        for k in range(1, len(parts) + 1)
    }
    manifests = {path for _, path in python_deps + js_deps}
    mentions = "\n".join(text for path, text in project.texts.items() if path not in manifests)
    js_code = "\n".join(
        "\n".join(f.lines) for f in project.files if f.language in ("javascript", "typescript")
    )
    unused = [
        (name, path)
        for name, path in python_deps
        if not _python_dependency_used(name, import_keys)
        and not re.search(rf"\b{re.escape(name)}\b", mentions)
    ] + [
        (name, path)
        for name, path in js_deps
        if not re.search(rf"['\"]{re.escape(name)}['\"/]", js_code + mentions)
        and name not in js_scripts
    ]
    found = [
        Finding(
            "unused-dependency",
            path,
            line_of(project.texts[path], name),
            name,
            "declared but never imported or invoked",
        )
        for name, path in unused
    ]
    return found, len(python_deps) + len(js_deps)


def _python_dependencies(project: Project) -> list[tuple[str, str]]:
    deps = []
    for path, text in project.texts.items():
        name = path.rsplit("/", 1)[-1]
        if name == "pyproject.toml":
            try:
                data = tomllib.loads(text)
            except tomllib.TOMLDecodeError:
                continue
            specs = list(data.get("project", {}).get("dependencies", []))
            specs += [
                k
                for k in data.get("tool", {}).get("poetry", {}).get("dependencies", {})
                if k != "python"
            ]
        elif name in ("requirements.txt", "requirements.in") and not LOCKFILE.search(text):
            specs = [
                s
                for s in (line.split("#", 1)[0].strip() for line in text.splitlines())
                if s and not s.startswith(("-", "git+", "http"))
            ]
        else:
            continue
        for spec in specs:
            match = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", spec)
            if match:
                deps.append((match.group(1), path))
    return deps


def _js_dependencies(project: Project) -> tuple[list[tuple[str, str]], str]:
    """Runtime dependencies from package.json files, plus the text of their npm scripts."""
    deps, scripts = [], []
    for path, text in project.texts.items():
        if path.rsplit("/", 1)[-1] != "package.json":
            continue
        try:
            data = json.loads(text)
        except json.JSONDecodeError:
            continue
        scripts += [str(v) for v in data.get("scripts", {}).values()]
        deps += [
            (name, path) for name in data.get("dependencies", {}) if not name.startswith("@types/")
        ]
    return deps, "\n".join(scripts)


def _python_dependency_used(dist: str, import_keys: set[str]) -> bool:
    name = _normalise(dist)
    if name in IMPLICIT_DEPENDENCIES or name.startswith(TOOLING_PREFIXES):
        return True
    candidates = {name, IMPORT_ALIASES.get(name, name)}
    candidates |= {name.removeprefix(p) for p in ("python_", "py")}
    candidates |= {name.removesuffix(s) for s in ("_python", "_py", "_sdk", "_client")}
    return bool(candidates & import_keys)


def _normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "_", name).lower()


def regex_capabilities(project: Project) -> list[Capability]:
    """Routes and commands in non-Python code, found by well-known framework idioms."""
    caps = []
    for f in project.prod:
        patterns = [(kind, rx) for langs, kind, rx in COMPILED_PATTERNS if f.language in langs]
        for number in sorted(f.code_lines) if patterns else ():
            line = f.lines[number - 1]
            caps += [
                Capability(kind, line.strip()[:60], f.path, number)
                for kind, rx in patterns
                if rx.search(line)
            ]
    for path, text in project.texts.items():
        if path.rsplit("/", 1)[-1] == "package.json":
            try:
                bins = json.loads(text).get("bin", {})
            except json.JSONDecodeError:
                continue
            names = [bins] if isinstance(bins, str) else list(bins)
            caps += [Capability("script", name, path, line_of(text, name)) for name in names]
    return caps
